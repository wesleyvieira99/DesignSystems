import {readFile,writeFile,readdir,mkdir,cp,rm} from 'node:fs/promises';
import {resolve} from 'node:path';
import {execFileSync} from 'node:child_process';
import {validateCatalog} from '../lib.js';
const root=resolve(import.meta.dirname,'..');
execFileSync('python3',[resolve(root,'scripts/package_example.py')],{stdio:'inherit'});
const files=(await readdir(resolve(root,'data'))).filter(f=>f.endsWith('.json')&&f!=='catalog.json').sort();
const entries=(await Promise.all(files.map(f=>readFile(resolve(root,'data',f),'utf8').then(JSON.parse)))).flat();
const errors=validateCatalog(entries);
if(errors.length)throw new Error(errors.join('\n'));
entries.sort((a,b)=>a.name.localeCompare(b.name,'pt-BR'));
const ids=new Set(entries.map(e=>e.id));
const unresolved=entries.flatMap(e=>(e.related||[]).filter(id=>!ids.has(id)).map(id=>`${e.id} -> ${id}`));
if(unresolved.length)console.warn('Relações não resolvidas (não serão exibidas):',unresolved.join(', '));
const catalog={updatedAt:'2026-10-28',count:entries.length,counts:Object.fromEntries([...new Set(entries.map(e=>e.category))].map(k=>[k,entries.filter(e=>e.category===k).length])),entries};
await writeFile(resolve(root,'data/catalog.json'),JSON.stringify(catalog));
await rm(resolve(root,'dist'),{recursive:true,force:true});await mkdir(resolve(root,'dist'),{recursive:true});
for(const file of ['index.html','styles.css','app.js','lib.js','backend.js','backend.css','assets','data','examples'])await cp(resolve(root,file),resolve(root,'dist',file),{recursive:true,filter:source=>!source.includes('__pycache__')&&!source.endsWith('.pyc')&&!source.endsWith('.sqlite3')});
await writeFile(resolve(root,'dist/.nojekyll'),'');
console.log(`Atlas pronto: ${entries.length} guias. ${JSON.stringify(catalog.counts)}`);
